package main

// Turning an archive.org item into an honest Play button.
//
// Yarr.It could already FIND games on archive.org (archive.go) and could
// already run one in EmulatorJS once a person pressed Play
// (web/src/resolvers/archive.js). What was missing is the thing in between:
// deciding, BEFORE the button is drawn, whether pressing it will actually
// produce a game. Today that decision is made twice -- once in archive.go's
// `ejsCores` and once in the browser's `IA_TO_EJS` -- and neither copy knows
// any of the four things that actually stop a game from playing.
//
// Measured against live archive.org on 2026-08-07, the shipped decision offers
// EmulatorJS for:
//
//     gamegear   602 items,  22 downloadable   (96% are stream-only)
//     a7800      739 items,  28 downloadable
//     lynx        97 items,   2 downloadable
//     psx      2,740 items, 148 downloadable   (and those are ~450 MB .chd)
//     coleco     266 items,  32 downloadable   (and every one needs a BIOS)
//
// Every other item in those five systems is a Play button that cannot work.
// That is what this file exists to stop.
//
// THE RULE: only offer Play when it will actually play. Where it will not, the
// API says which of the reasons applies, in words a UI can show, and -- when
// the Internet Archive's own player can still run it -- routes there instead.
// A refusal that names an alternative is not a dead end.
//
// ---------------------------------------------------------------------------
// WHY THIS IS GO HERE AND NOT A ROM HUB PLUGIN
// ---------------------------------------------------------------------------
//
// ROM Hub is ROMarr's plugin factory, and the archive.org plugin it already
// ships is right and is reused rather than reimplemented -- see the two tables
// below, both of which are its work. But a ROM Hub plugin cannot be the answer
// to this particular question, for reasons that are structural rather than
// preference:
//
//   * A plugin never talks to a library server and returns a DESCRIPTION of
//     work for the Hub to execute. The playability verdict is not a plugin
//     concern at all -- in ROM Hub it lives in the host, `rom_hub/playability.py`.
//   * The Hub is a Python sidecar that an operator installs beside their own
//     library server, with a seccomp-confined subprocess per plugin. A Yarr.It
//     visitor is an anonymous browser hitting a Go binary on a VPS. There is no
//     Hub in that path and putting one there would mean every visitor needs the
//     thing this work exists to remove.
//   * The plugin's `stream` capability already answers the question it is
//     entitled to answer -- "resolve this item to something that plays" -- and
//     answers it by returning the Archive's own details page. That is correct
//     for the Hub and is exactly the `routeArchive` branch below.
//
// So: the KNOWLEDGE comes from ROM Hub (and drift is caught by a test that
// reads its tables), and the DECISION runs at the edge, per request, for a
// visitor who installs nothing.
//
// ---------------------------------------------------------------------------
// WHY THERE IS A CORE MAP HERE WHEN provider_romm.go REFUSED TO KEEP ONE
// ---------------------------------------------------------------------------
//
// provider_romm.go deliberately does not copy RomM's 81-platform core map,
// because RomM's own player page answers the per-platform question and a second
// copy could only drift from it. That reasoning does not transfer, because here
// there is nobody to ask:
//
//   * archive.org knows nothing about EmulatorJS. Its `emulator` field is its
//     own emulator id (`megadriv`, `a2600p`, `vice-resid`).
//   * There is no RomM in this path. The visitor runs nothing.
//
// Somebody has to hold the translation, so the honest question is not whether
// to have a table but how to keep it true. Three defences, all of them tests
// rather than intentions (see play_archive_test.go):
//
//   1. Every core value must be one of the 36 systems EmulatorJS's own
//      `getCores()` defines. This is the guard for the trap that cost a real
//      library 1,451 games: `gbc`, `pcecd`, `vice_x64` and `mame2003` all look
//      like core names and none of them exists.
//   2. Every platform slug must be one ROM Hub's `playability.EJS_CORES` also
//      considers playable. If ROM Hub says a platform is catalogue-only and we
//      offer Play for it, one of the two is wrong and the test says so.
//   3. Every archive.org emulator id must be one ROM Hub's archive-org plugin
//      maps, so this table can never quietly learn an id the plugin refuses.
//
// The table is NOT generated by composing those two, and that is deliberate: it
// was tried, and composing through libretro core names is ambiguous in exactly
// the dangerous direction. `genesis_plus_gx` and `picodrive` each appear under
// several EmulatorJS systems, so a mechanical join resolves `genesis`,
// `megadriv`, `32x`, `sms` and `gamegear` all to `segaMS` -- a Mega Drive game
// booted as a Master System, which is the failure that boots happily and then
// runs nothing. The composition is a cross-check, never a generator.

