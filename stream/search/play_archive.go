// --- what the caller is told -----------------------------------------------

// playReason is one sentence about why something was refused, plus a code a
// client can branch on without reading English.
type playReason struct {
	Code   string `json:"code"`
	Detail string `json:"detail"`
}

// playROM is the file, and only ever appears when it is actually fetchable.
type playROM struct {
	Name string `json:"name"`
	// URL is what the player loads: the relay, because archive.org sends no
	// Access-Control-Allow-Origin on downloads and a WASM emulator fetches the
	// ROM itself.
	URL string `json:"url"`
	// Direct is the same file at archive.org, so a caller that is not a browser
	// (a native client, a test) can skip the relay and cost us nothing. EMPTY
	// for an item the Archive marks stream-only: playing it is permitted and
	// handing somebody the file is what is not.
	Direct    string `json:"direct,omitempty"`
	SizeBytes int64  `json:"sizeBytes"`
}

type playAnswer struct {
	ID    string `json:"id"`
	Title string `json:"title,omitempty"`

	// Domain and Type come from schema.json's frozen game vocabulary. An item
	// on archive.org is a concrete dump of one game for one machine, which is a
	// "release", not the abstract "game" -- the same call provider_romm.go makes
	// for a RomM ROM.
	Domain string `json:"domain"`
	Type   string `json:"type"`

	// Emulator is archive.org's own id, carried verbatim so a refusal can name
	// it and somebody can look it up.
	Emulator string `json:"emulator,omitempty"`
	Platform string `json:"platform,omitempty"`
	System   string `json:"system,omitempty"`

	// Playable is the whole point, and it means "pressing Play produces a
	// game", by either route.
	Playable bool   `json:"playable"`
	Route    string `json:"route"`

	// Core is the EmulatorJS system name, present only on the emulatorjs route.
	Core string `json:"core,omitempty"`
	// CoreFile is the core EmulatorJS will download for that system. Carried so
	// the claim is checkable rather than asserted -- a name that is valid and a
	// core that is published are different things.
	CoreFile string   `json:"coreFile,omitempty"`
	ROM      *playROM `json:"rom,omitempty"`

	// Embed is the Internet Archive's own player, present whenever the item
	// declares an emulator -- including on the emulatorjs route, so a client can
	// offer it as the fallback when a phone's memory will not hold a core.
	// It is what makes the player switch possible: two routes, both real.
	Embed string `json:"embed,omitempty"`

	// BiosNeeded is set when firmware is the ONLY thing between this item and
	// our own player. It is an invitation rather than an error: the file is not
	// ours to ship and is the console owner's to supply, so naming it turns a
	// refusal into an instruction. Absent when the item would fail for some
	// other reason too, because offering somebody a way to unblock a game that
	// would then be refused for its size is a worse lie than saying no.
	BiosNeeded *playBIOS `json:"biosNeeded,omitempty"`

	// Guide is what the game is and which key is fire. See play_guide.go.
	Guide *playGuide `json:"guide,omitempty"`

	// Touch says whether the offered route has on-screen controls. Their player
	// expects a keyboard, so on a phone a console game there is something you
	// can watch and not play; that is a caveat about the route, not a lie about
	// whether it plays.
	Touch bool `json:"touch"`

	// StreamOnly carries the Internet Archive's own "play but do not download"
	// marker. It is NOT a refusal and never affects the route: it is a fact
	// about what a client may offer to do with the file, and the one thing it
	// forbids -- publishing a direct link -- is already done by leaving
	// ROM.Direct empty.
	StreamOnly bool `json:"streamOnly,omitempty"`

	// Reasons is never empty unless Route is emulatorjs. Every downgrade and
	// every refusal is named here, in the order they were found, so a UI can be
	// honest without inventing an explanation of its own.
	Reasons []playReason `json:"reasons,omitempty"`
}

// directIfDownloadable withholds the direct link for an item the Archive marks
// stream-only. One line, in one place, so "play yes, download no" cannot be
// half-implemented.
func directIfDownloadable(direct string, streamOnly bool) string {
	if streamOnly {
		return ""
	}
	return direct
}

// --- archive.org metadata ---------------------------------------------------

// Only the fields this decision turns on, and three of them are RawMessage
// because archive.org genuinely sends more than one shape for each:
//
//	size            a decimal STRING, or absent entirely
//	collection      a list, except when the item is in exactly one, where
//	                it is a bare string
//	emulator_ext    a string, except when an item ships more than one
//	                playable form, where it is a list -- `f-zero-x-usa_202506`
//	                declares ["zip","z64"]
//
// The last one is not a curiosity. Declaring it as a `string` makes the whole
// decode fail on that item, and a decode failure reads as "the Archive did not
// answer" -- so one unusual item would be reported as an outage.
type playItemMetadata struct {
	Metadata struct {
		Identifier  string          `json:"identifier"`
		Title       string          `json:"title"`
		MediaType   string          `json:"mediatype"`
		Emulator    string          `json:"emulator"`
		EmulatorExt json.RawMessage `json:"emulator_ext"`
		Collection  json.RawMessage `json:"collection"`
		AccessRestr json.RawMessage `json:"access-restricted-item"`

		// The three fields the guide is built from. `emulator_instructions` is
		// the Archive's own per-game control notes and is the single most
		// valuable field on the whole item -- measured live 2026-08-07, River
		// Raid's says which key is fire. `controller` is "joystick", "keyboard"
		// or "paddle". See play_guide.go.
		//
		// All three are RawMessage for the reason emulator_ext is: archive.org
		// sends a bare string when there is one value and a list when there is
		// more than one, and an item with two descriptions must not decode as an
		// outage. That trap has already been paid for once in this file.
		Description          json.RawMessage `json:"description"`
		EmulatorInstructions json.RawMessage `json:"emulator_instructions"`
		Controller           json.RawMessage `json:"controller"`
	} `json:"metadata"`
	Files []struct {
		Name   string `json:"name"`
		Format string `json:"format"`
		Size   string `json:"size"`
	} `json:"files"`
}

// jsonStrings reads a field archive.org sends as either one string or a list
// of them. Empty means the field was absent or unusable, which callers must
// treat as "the Archive did not say" rather than as a default.
func jsonStrings(raw json.RawMessage) []string {
	if len(raw) == 0 {
		return nil
	}
	var list []string
	if err := json.Unmarshal(raw, &list); err == nil {
		out := make([]string, 0, len(list))
		for _, s := range list {
			if s = strings.TrimSpace(s); s != "" {
				out = append(out, s)
			}
		}
		return out
	}
	var one string
	if err := json.Unmarshal(raw, &one); err == nil {
		if one = strings.TrimSpace(one); one != "" {
			return []string{one}
		}
	}
	return nil
}

// extensions is what the Archive says the payload is, normalised. In declared
// order, because when an item offers several the Archive's own ordering is the
// only preference anyone has stated.
func (m *playItemMetadata) extensions() []string {
	raw := jsonStrings(m.Metadata.EmulatorExt)
	out := make([]string, 0, len(raw))
	for _, ext := range raw {
		ext = strings.ToLower(strings.TrimPrefix(strings.TrimSpace(ext), "."))
		if ext != "" {
			out = append(out, ext)
		}
	}
	return out
}

// collections reads archive.org's `collection`, which is a list of strings
// except when the item is in exactly one, where it is a bare string.
func (m *playItemMetadata) collections() []string {
	return jsonStrings(m.Metadata.Collection)
}

// streamOnly reports the Archive's own "you may play this but not download it"
// marker.
//
// This is a POLICY signal and is treated as one. The bytes are in fact served
// -- measured: a stream-only Game Gear ROM downloads with HTTP 200 -- so this is
// not a technical failure we are reporting but a restriction we are honouring.
// Relaying such a file would republish it from our host, which is precisely what
// the marker asks us not to do. ROM Hub's importer refuses on the same signal
// for the same reason.
//
// Both spellings are read because both appear: the `stream_only` collection and
// `access-restricted-item`. On every item sampled they agree, and taking either
// as sufficient means a future item that carries only one is still honoured.
func (m *playItemMetadata) streamOnly() bool {
	for _, c := range m.collections() {
		if strings.EqualFold(strings.TrimSpace(c), "stream_only") {
			return true
		}
	}
	if len(m.Metadata.AccessRestr) > 0 {
		var s string
		if err := json.Unmarshal(m.Metadata.AccessRestr, &s); err == nil {
			return strings.EqualFold(strings.TrimSpace(s), "true")
		}
		var b bool
		if err := json.Unmarshal(m.Metadata.AccessRestr, &b); err == nil {
			return b
		}
	}
	return false
}

// payload picks the file that is the game.
//
// The rule is ROM Hub's importer's, and it is the Archive's own assertion
// rather than our guess: `emulator_ext` names the payload extension, and among
// the files that match it the largest wins with a missing size sorting last, so
// a metadata stub can never outrank the actual game. The name breaks ties, so
// the same item always resolves to the same file.
//
// Deliberately NOT the browser's `bestFile` heuristic. That works, but it works
// by knowing a list of ROM extensions -- and `.bin` is ColecoVision, Atari 2600,
// Mega Drive and PC Engine at once. Where the Archive has told us which file it
// is, asking is better than inferring.
// When the Archive declares several extensions they are tried in the order it
// declared them, and the first that matches any file wins. That ordering is the
// only preference anybody has stated, and preferring one ourselves -- biggest,
// or "the one that is not a zip" -- would be us overruling the source about its
// own item.
func (m *playItemMetadata) payload() (name string, size int64, ok bool) {
	for _, ext := range m.extensions() {
		suffix := "." + ext
		best, bestSize := "", int64(-1)
		for _, f := range m.Files {
			if !strings.HasSuffix(strings.ToLower(f.Name), suffix) {
				continue
			}
			// A bare ".zip" has no basename; there is nothing to name or fetch.
			if base := path.Base(f.Name); base == "" || base == suffix {
				continue
			}
			size := parseArchiveSize(f.Size)
			if size > bestSize || (size == bestSize && f.Name < best) {
				best, bestSize = f.Name, size
			}
		}
		if best == "" {
			continue
		}
		if bestSize < 0 {
			bestSize = 0
		}
		return best, bestSize, true
	}
	return "", 0, false
}

// parseArchiveSize reads `files[].size`, which is a decimal string or absent.
// Absent is -1 rather than 0 so it sorts below every real size.
func parseArchiveSize(raw string) int64 {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return -1
	}
	var n int64
	if _, err := fmt.Sscanf(raw, "%d", &n); err != nil || n < 0 {
		return -1
	}
	return n
}

