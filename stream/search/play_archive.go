// playArchive answers "can this be played, and how".
type playArchive struct {
	client *http.Client
	// metadataBase is where item metadata is read from. A field so a test can
	// point it at a local server; there is no other reason to change it.
	metadataBase string
	downloadBase string
	embedBase    string

	// firmware is the household's own library, if it has one. nil is a
	// first-class value: every path that touches it degrades to the next source
	// and finally to the bring-your-own offer, which is what this endpoint did
	// before there was anything to ask. See play_bios.go.
	firmware biosLibrary
	// diskFirmware is the operator's own firmware directory on this machine,
	// when they have one and this service can see it. nil on the hosted
	// instance, which cannot see anybody's disk and does not pretend to.
	diskFirmware biosLibrary
	// publicFirmware is the Internet Archive's own player's firmware, relayed.
	// It needs no configuration and no credential, so unlike the line above it
	// is present by default. See play_bios_archive.go.
	publicFirmware biosLibrary
}

func newPlayArchive(client *http.Client) *playArchive {
	if client == nil {
		client = &http.Client{Timeout: playMetadataTimeout}
	}
	return &playArchive{
		client:       client,
		metadataBase: "https://archive.org/metadata/",
		downloadBase: "https://archive.org/download/",
		embedBase:    "https://archive.org/embed/",
		// Both firmware sources are left nil here and wired in
		// registerPlayRoutes. A constructor that reached the network by default
		// would make every test that builds one reach the network too, and a
		// test suite that quietly depends on archive.org being up is a suite
		// that fails for reasons that have nothing to do with the change.
	}
}

// registerPlayRoutes wires the play endpoints.
//
// Both are catalogue data in the sense cors.go draws the line: they describe
// what exists on archive.org and reveal nothing about this household, so a
// television or somebody else's client must be able to read them from another
// origin. They spend no disk and no relay bandwidth -- resolving costs one
// metadata request, and the ROM bytes only ever move when a player actually
// fetches the URL through /bridge/iptv, which has its own budget and its own
// concurrency gate.
//
// If the operator wants these behind the same reader gate as /api/pages, wrap
// them the way main.go wraps that one; nothing here depends on being open.
func registerPlayRoutes(mux *http.ServeMux) {
	p := newPlayArchive(nil)

	// The firmware the Internet Archive's own player uses. Unconditional,
	// because it needs nothing from anybody: no credential, no setting, no
	// file, and no operator who knew to configure it. A household with no
	// library server still gets a ColecoVision that plays, which is the whole
	// point of it being here.
	p.publicFirmware = newArchiveFirmware(nil)

	// The operator's own firmware tree, if this service can see one. A
	// self-hoster's whole collection with one environment variable and no
	// import step; absent on the hosted instance, which has no such disk.
	if dir := newDirFirmwareFromEnv(); dir != nil {
		p.diskFirmware = dir
		// Read once at startup, off the request path, so the first person to
		// open a ColecoVision item is not the one who discovers the tree.
		go dir.Firmware(context.Background(), "coleco")
	}

	// The household's own firmware, from the RomM the operator has already
	// configured. nil when there is none, and everything below is written so
	// that nil is simply the way it worked yesterday.
	if lib := newRommFirmwareFromEnv(); lib != nil {
		p.firmware = lib
		// Built once, off the request path, so the first person to open a
		// ColecoVision item is not the one who discovers the library. A failure
		// here costs nothing: the next real verdict asks again.
		go func() {
			ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
			defer cancel()
			lib.Warm(ctx)
		}()
	}
	p.register(mux)
}

func (p *playArchive) register(mux *http.ServeMux) {
	mux.HandleFunc("/api/play/archive", publicCORS(p.handleArchive))
	mux.HandleFunc("/api/play/systems", publicCORS(p.handleSystems))
	// One firmware file per machine per source, relayed. The method is pinned
	// because this is a read and nothing else; every path value is checked
	// against an index that was built elsewhere rather than used to address
	// anything, so this is not a proxy.
	mux.HandleFunc("GET /api/play/bios/{source}/{system}/{file}", publicCORS(p.handleBIOS))
	mux.HandleFunc("HEAD /api/play/bios/{source}/{system}/{file}", publicCORS(p.handleBIOS))
}

// playOptions are the things only the CALLER can know, because they are facts
// about the browser asking rather than about the item.
//
// Both of them turn a refusal into a game, and neither can be guessed from here:
// a BIOS lives in one visitor's browser storage and nowhere else, and whether a
// page is cross-origin isolated is a property of the document that loaded, not
// of this server. Defaulting both to the pessimistic value is deliberate -- an
// answer computed without them is the answer for a visitor who has neither, and
// that is the one that must never be optimistic.
type playOptions struct {
	// BIOS is the set of EmulatorJS system names the caller holds firmware for.
	BIOS map[string]bool
	// Isolated is `crossOriginIsolated` in the calling document. When true,
	// SharedArrayBuffer exists and the threaded cores (DOS, PSP) can run.
	Isolated bool
}

func (o playOptions) hasBIOS(core string) bool {
	return o.BIOS != nil && o.BIOS[core]
}

// parsePlayOptions reads the two capability declarations off the query string.
//
// A DECLARATION, not a promise: a client claiming a BIOS it does not have gets
// our player and a game that will not boot, which is its own doing and its own
// to fix. Nothing here is trusted with anything but the answer to "which button
// do I draw", and being wrong costs that client one click.
func parsePlayOptions(q url.Values) playOptions {
	opts := playOptions{Isolated: q.Get("isolated") == "1"}
	for _, field := range q["bios"] {
		for _, name := range strings.Split(field, ",") {
			name = strings.TrimSpace(name)
			if name == "" {
				continue
			}
			if _, known := biosRequirements[name]; !known {
				// Only the three machines that are actually blocked on firmware
				// can be unblocked by it. Accepting an arbitrary name would let
				// a typo look like a capability.
				continue
			}
			if opts.BIOS == nil {
				opts.BIOS = map[string]bool{}
			}
			opts.BIOS[name] = true
		}
	}
	return opts
}

// handleArchive resolves one item.
func (p *playArchive) handleArchive(w http.ResponseWriter, r *http.Request) {
	q := r.URL.Query()
	id := archiveIdentifier(q.Get("id"))
	if id == "" {
		writeJSON(w, http.StatusBadRequest, map[string]string{
			"error": "id is required: an archive.org identifier, or any archive.org item URL",
		})
		return
	}
	writeJSON(w, http.StatusOK, p.ResolveWith(r.Context(), id, parsePlayOptions(q)))
}

// handleSystems publishes the table.
//
// It exists so a client can decide whether to draw a Play affordance at all
// before spending a metadata request -- a search result already carries its
// platform -- and so the refusals are inspectable by somebody who wants to know
// why their favourite machine is not offered, without reading this file.
func (p *playArchive) handleSystems(w http.ResponseWriter, r *http.Request) {
	type systemView struct {
		Emulator string `json:"emulator"`
		Platform string `json:"platform"`
		System   string `json:"system"`
		Core     string `json:"core,omitempty"`
		CoreFile string `json:"coreFile,omitempty"`
		Playable bool   `json:"playable"`
		Reason   string `json:"reason,omitempty"`
		Detail   string `json:"detail,omitempty"`
		// Unlockable says the refusal is about this visitor rather than about
		// this machine, and names what would lift it. It is what lets a client
		// draw a "add your ColecoVision BIOS" screen without a second table of
		// which machines that could possibly apply to.
		Unlockable string    `json:"unlockable,omitempty"`
		BIOS       *playBIOS `json:"bios,omitempty"`
	}
	out := make([]systemView, 0, len(archivePlaySystems))
	for emulator, plat := range archivePlaySystems {
		v := systemView{
			Emulator: emulator, Platform: plat.Platform, System: plat.Label,
		}
		switch {
		case plat.Core == "":
			v.Reason = reasonNoCore
			v.Detail = noCoreDetail(plat)
		case blockedSystems[plat.Core].Reason != "":
			b := blockedSystems[plat.Core]
			v.Reason, v.Detail = b.Reason, b.Detail
			switch b.Reason {
			case reasonNeedsBIOS:
				if need, ok := biosRequirements[plat.Core]; ok {
					v.Unlockable, v.BIOS = "bios", &need
				}
			case reasonNeedsIsolation:
				v.Unlockable = "isolation"
			}
			// The core is named ONLY when it could actually be used -- i.e.
			// when the refusal is liftable. Arcade is refused for a reason no
			// visitor can lift, and publishing `mame2003_plus` beside that
			// refusal would advertise a core this endpoint will never choose.
			if v.Unlockable != "" {
				v.Core = plat.Core
				v.CoreFile = emulatorJSSystems[plat.Core]
			}
		default:
			v.Playable = true
			v.Core = plat.Core
			v.CoreFile = emulatorJSSystems[plat.Core]
		}
		out = append(out, v)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Emulator < out[j].Emulator })

	// Every machine a visitor could unblock by supplying firmware, listed once
	// rather than once per emulator id, so a settings screen has something to
	// iterate that is not the 90-row table above.
	biosList := make([]playBIOS, 0, len(biosRequirements))
	for _, need := range biosRequirements {
		biosList = append(biosList, need)
	}
	sort.Slice(biosList, func(i, j int) bool { return biosList[i].System < biosList[j].System })

	writeJSON(w, http.StatusOK, map[string]any{
		"domain":  "game",
		"type":    "release",
		"systems": out,
		"bios":    biosList,
		// The ceiling is part of the contract: a client that knows it can say
		// "too big to play here" about a file it already has the size of.
		"maxRelayBytes": maxRelayROMBytes,
	})
}

// Resolve answers for a visitor who has declared nothing -- no BIOS, no
// cross-origin isolation. That is the conservative answer and the right default:
// every capability below only ever turns a `no` into a `yes`, so an answer
// computed without them can be too pessimistic and never too optimistic.
func (p *playArchive) Resolve(ctx context.Context, id string) playAnswer {
	return p.ResolveWith(ctx, id, playOptions{})
}

// ResolveWith is the whole decision, and it is ordered so that the reason a
// person is given is the FIRST thing that is wrong rather than the last check to
// run.
func (p *playArchive) ResolveWith(ctx context.Context, id string, opts playOptions) playAnswer {
	answer := playAnswer{ID: id, Domain: "game", Type: "release", Route: routeNone}

	meta, err := p.metadata(ctx, id)
	if err != nil {
		answer.Reasons = append(answer.Reasons, playReason{
			Code:   reasonUpstream,
			Detail: "the Internet Archive did not answer for this item, so whether it plays is unknown.",
		})
		return answer
	}
	if meta.Metadata.Identifier == "" && meta.Metadata.Title == "" && len(meta.Files) == 0 {
		// A 200 carrying `{}` is how archive.org answers for an identifier that
		// does not exist.
		answer.Reasons = append(answer.Reasons, playReason{
			Code:   reasonNotFound,
			Detail: "the Internet Archive has no item with this identifier.",
		})
		return answer
	}
	answer.Title = strings.TrimSpace(meta.Metadata.Title)

	// The guide is attached HERE, before any refusal, and it is attached on
	// every path from this point on. A person sent to the Archive's own player
	// needs the instructions at least as much as one who got ours -- more,
	// because that player has no on-screen pad to experiment with -- and an item
	// that plays nowhere is still a game somebody may want to read about.
	plat, known := archivePlaySystems[strings.ToLower(strings.TrimSpace(meta.Metadata.Emulator))]
	answer.Guide = p.guideFor(meta, plat.Core, plat.Label)

	// 1. Does the Archive itself say this is an emulated item? Their `emulator`
	//    field IS the definition of "runs in a browser here", not a proxy for
	//    it. Nothing is guessed from a filename: that is what boots a
	//    ColecoVision game as an NES.
	emulator := strings.TrimSpace(meta.Metadata.Emulator)
	if emulator == "" {
		answer.Reasons = append(answer.Reasons, playReason{
			Code: reasonNotEmulated,
			Detail: "this item is not an emulated one -- the Internet Archive " +
				"declares no emulator for it, so there is nothing to run.",
		})
		return answer
	}
	answer.Emulator = emulator

	// From here the Archive's own player can run it, so `none` is off the table
	// and the worst outcome is `archive`.
	answer.Embed = p.embedBase + url.PathEscape(id)

	answer.Platform, answer.System = plat.Platform, plat.Label

	// 2. Do we know the machine, and is there a core for it?
	switch {
	case !known:
		return p.viaArchive(answer, playReason{
			Code: reasonNoCore,
			Detail: fmt.Sprintf(
				"the Internet Archive runs this on %q, which is not a machine "+
					"this player has a core for. Their own player will run it.",
				emulator),
		})
	case plat.Core == "":
		return p.viaArchive(answer, playReason{
			Code: reasonNoCore, Detail: noCoreDetail(plat),
		})
	}

	// 3. Is the core one that cannot work in an ordinary tab? A missing BIOS is
	//    the dangerous case: the emulator starts, draws its own error screen and
	//    streams it at a healthy frame rate, so nothing downstream can tell that
	//    from a working game.
	//
	//    Two of the three reasons a core is blocked are not facts about the core
	//    at all -- they are facts about the visitor, and the visitor can change
	//    them. Firmware we may not ship is firmware its owner may supply; a page
	//    that is not cross-origin isolated is a page that could be. Where the
	//    caller has declared the missing piece, the block does not apply, and
	//    where it has not, the answer names what would lift it.
	//    Firmware now has TWO possible owners and exactly one code path. A file
	//    the visitor added by hand and a file the household's library already
	//    holds unblock the machine identically; all that differs is where the
	//    client fetches the bytes, which is the last thing decided and the only
	//    thing carried out. Asked once, here, so the refusal branch and the
	//    success branch can never disagree about whether firmware was available.
	bios := p.firmwareFor(ctx, plat.Core, opts)
	if b, blocked := blockedSystems[plat.Core]; blocked && !p.unblocked(b, plat.Core, opts, bios != nil) {
		if need, ok := biosRequirements[plat.Core]; ok && b.Reason == reasonNeedsBIOS {
			// Named only when firmware really is the last obstacle. See the
			// field comment: pointing somebody at a 460 MB disc image's BIOS is
			// a longer route to the same refusal, and the refusal would arrive
			// after they had gone and found the file.
			// Stream-only is no longer part of this: such an item plays here
			// perfectly well, so firmware really is the last obstacle for it.
			_, size, hasPayload := meta.payload()
			if hasPayload && size <= maxRelayROMBytes {
				answer.BiosNeeded = &need
			}
		}
		return p.viaArchive(answer, playReason{Code: b.Reason, Detail: b.Detail})
	}

	// 4. What the Archive's stream-only marker actually asks for.
	//
	//    It used to send the item to their player, and that was wrong. The
	//    distinction the Archive draws is PLAY YES, DOWNLOAD NO -- and their own
	//    Emularity player fetches the ROM into the browser's memory to run it,
	//    which is precisely what ours does. Refusing to run it here did not
	//    honour anything; it just meant the same act happened on their page
	//    instead of ours, on a player with no touch controls.
	//
	//    So the marker is carried rather than obeyed as a refusal, and it is
	//    obeyed where it means something: no direct link is published for a
	//    stream-only item, so there is nothing to save and nothing to hand on.
	//    That is the line that matters, and it costs nothing -- nobody wants a
	//    download button on a game they are already playing.
	//
	//    (The bytes were never the obstacle: a stream-only Game Gear ROM was
	//    measured downloading with HTTP 200. This was always a policy signal.)
	streamOnly := meta.streamOnly()

	// 5. Is there actually a file to play?
	name, size, ok := meta.payload()
	if !ok {
		detail := fmt.Sprintf(
			"this item declares no file for %s to load, so there is nothing to "+
				"hand the emulator.", plat.Label)
		if exts := meta.extensions(); len(exts) > 0 {
			detail = fmt.Sprintf(
				"this item names %q as its payload but has no file with that "+
					"extension, so there is nothing to hand the emulator.",
				strings.Join(exts, ", "))
		}
		return p.viaArchive(answer, playReason{Code: reasonNoPayload, Detail: detail})
	}

	// 6. Is it small enough to be worth relaying?
	if size > maxRelayROMBytes {
		return p.viaArchive(answer, playReason{
			Code: reasonTooLarge,
			Detail: fmt.Sprintf(
				"%s is %s, past the %s this relay will carry for one game -- a "+
					"disc image rather than a cartridge. Their player streams it "+
					"instead.",
				path.Base(name), humanBytes(size), humanBytes(maxRelayROMBytes)),
		})
	}

	direct := p.downloadBase + url.PathEscape(id) + "/" + archiveFilePath(name)
	answer.StreamOnly = streamOnly
	answer.Playable = true
	answer.Route = routeEmulatorJS
	answer.Core = plat.Core
	answer.CoreFile = emulatorJSSystems[plat.Core]
	answer.Touch = true
	// Carried on the way OUT as well as on the way in: this route was reached
	// because firmware was available, and the client has to know WHICH file to
	// hand the emulator and where to get it. Without this it would have to
	// re-derive the mapping from `core`, which is a second copy of a table.
	if need, ok := biosRequirements[plat.Core]; ok && bios != nil {
		need.Source, need.File, need.URL, need.SizeBytes, need.Options =
			bios.Source, bios.Name, bios.URL, bios.Size, bios.Options
		if bios.Detail != "" {
			// The generic sentence is an invitation to supply a file. Where
			// nobody has to, it would be describing something that is not
			// happening.
			need.Detail = bios.Detail
		}
		answer.BiosNeeded = &need
	}
	answer.ROM = &playROM{
		Name: path.Base(name),
		URL:  "/bridge/iptv?u=" + url.QueryEscape(direct),
		// Direct is the file at archive.org, for a caller that is not a browser
		// and can skip our relay -- and it is WITHHELD for a stream-only item,
		// because a direct link is exactly the download the Archive asks us not
		// to offer. The relay URL still works: that is the play, not the
		// download, and it is fetched by the emulator rather than by a person.
		Direct:    directIfDownloadable(direct, streamOnly),
		SizeBytes: size,
	}
	return answer
}

// unblocked reports whether the one missing thing has been supplied.
//
// `haveBIOS` is the answer for BOTH owners of firmware -- the visitor's own file
// and the household library's -- decided once by firmwareFor and passed in, so
// there is one condition here rather than two that could drift apart.
//
// Only two of the three block reasons can be lifted this way, and the third is
// the interesting one: `no_core` -- arcade -- stays blocked whatever anybody
// declares or holds, because a MAME romset must match the build reading it and
// no firmware changes that. Enumerating the liftable reasons rather than
// defaulting to "lift it" is what keeps that true if a fourth reason is added.
func (p *playArchive) unblocked(b blockedSystem, core string, opts playOptions, haveBIOS bool) bool {
	switch b.Reason {
	case reasonNeedsBIOS:
		return haveBIOS
	case reasonNeedsIsolation:
		return opts.Isolated
	default:
		return false
	}
}

// viaArchive downgrades to the Internet Archive's own player, carrying the
// reason. It is still Playable: their Emularity player is a real game in a real
// browser, and calling it unplayable would be its own dishonesty.
func (p *playArchive) viaArchive(answer playAnswer, reason playReason) playAnswer {
	answer.Playable = true
	answer.Route = routeArchive
	// Their player expects a keyboard and offers no on-screen pad. That is the
	// one thing a phone needs to know before it is told this "plays".
	answer.Touch = false
	answer.Reasons = append(answer.Reasons, reason)
	return answer
}

// noCoreDetail names the machine rather than shrugging. ROM Hub's
// playability.NO_EQUIVALENT records, for each of these, why it was not refiled
// under a platform that does play -- a temptation that is always available and
// always wrong.
func noCoreDetail(plat archivePlatform) string {
	name := plat.Label
	if name == "" {
		name = plat.Platform
	}
	if name == "" {
		return "there is no browser emulator core for this machine. The " +
			"Internet Archive's own player will run it."
	}
	return fmt.Sprintf(
		"there is no browser emulator core for the %s, and no other machine's "+
			"core will run its software. The Internet Archive's own player will "+
			"run it.", name)
}

// metadata fetches one item.
func (p *playArchive) metadata(ctx context.Context, id string) (*playItemMetadata, error) {
	ctx, cancel := context.WithTimeout(ctx, playMetadataTimeout)
	defer cancel()

	req, err := http.NewRequestWithContext(ctx, http.MethodGet,
		p.metadataBase+url.PathEscape(id), nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("Accept", "application/json")
	req.Header.Set("User-Agent", "yarr.it/1.0 (+https://yarrit.com)")

	resp, err := p.client.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("archive.org metadata %s: status %d", id, resp.StatusCode)
	}

	var m playItemMetadata
	if err := json.NewDecoder(resp.Body).Decode(&m); err != nil {
		// Rate limiting and maintenance pages both arrive as 200 + HTML, so a
		// decode failure is an upstream problem rather than a missing item.
		return nil, fmt.Errorf("archive.org metadata %s: %w", id, err)
	}
	return &m, nil
}

// archiveFilePath escapes a filename for a URL path without escaping the
// slashes that separate directories inside an item.
func archiveFilePath(name string) string {
	parts := strings.Split(name, "/")
	for i, part := range parts {
		parts[i] = url.PathEscape(part)
	}
	return strings.Join(parts, "/")
}

// humanBytes renders a size the way a sentence wants it.
func humanBytes(n int64) string {
	const unit = 1024
	if n < unit {
		return fmt.Sprintf("%d B", n)
	}
	div, exp := int64(unit), 0
	for m := n / unit; m >= unit && exp < 3; m /= unit {
		div *= unit
		exp++
	}
	return fmt.Sprintf("%.1f %ciB", float64(n)/float64(div), "KMGT"[exp])
}
